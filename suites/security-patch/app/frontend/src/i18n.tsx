const I18nContext = createContext<I18nContextType>({
  lang: "en",
  setLang: () => {},
  t: (k) => k,
  label: (_p, v) => v,
})

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const saved = localStorage.getItem("ola_lang") as Lang
      if (saved === "en" || saved === "zh") return saved
    } catch {
      // ignore
    }
    return "en"
  })

  useEffect(() => {
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en"
    document.title = DICT[lang]["nav.brand"]
  }, [lang])

  function setLang(newLang: Lang) {
    setLangState(newLang)
    try {
      localStorage.setItem("ola_lang", newLang)
    } catch {
      // ignore
    }
  }

  function t(key: string, params?: Record<string, string | number>): string {
    let str = DICT[lang][key] || DICT.en[key] || key
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        str = str.replace(new RegExp(`\\{${k}\\}`, "g"), () => String(v))
      }
    }
    return str
  }

  function label(prefix: string, value: string): string {
    const key = `${prefix}.${value}`
    return DICT[lang][key] || DICT.en[key] || value
  }

  return <I18nContext.Provider value={{ lang, setLang, t, label }}>{children}</I18nContext.Provider>
}

export function useI18n() {
  return useContext(I18nContext)
}
